package main

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

// Removing the last dependency used to leave its bindings indefinitely because
// sync only tracked dependencies that were still declared.
func TestSyncRetiresGeneratedDependencyBindingsAndPreservesAuthoredFiles(t *testing.T) {
	root := t.TempDir()
	generated := "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage client\n"
	files := map[string]string{
		"code/external/mod/retired/api.pb.go":  generated,
		"code/external/mod/retired/helpers.go": "package client\n",
		"code/external/mod/retired/README.md":  "Authored notes\n",
		"code/external/mod/current/api.pb.go":  generated,
	}
	for name, body := range files {
		path := filepath.Join(root, name)
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
		require.NoError(t, os.WriteFile(path, []byte(body), 0o644))
	}
	tx, err := newSyncTransaction(root, "mod/service")
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, tx.Close()) })
	require.NoError(t, tx.CopyInput("code/external/mod/current"))
	require.NoError(t, tx.TrackDirectory("code/external/mod/current"))
	require.NoError(t, trackRetiredDependencyBindings(tx, "code"))
	changed, err := tx.ChangedFiles()
	require.NoError(t, err)
	require.Equal(t, []string{"mod/service/code/external/mod/retired/api.pb.go"}, changed)
	require.FileExists(t, filepath.Join(root, "code/external/mod/retired/api.pb.go"), "planning must not mutate the checkout")
	require.NoError(t, tx.Apply())
	require.NoFileExists(t, filepath.Join(root, "code/external/mod/retired/api.pb.go"))
	for name, body := range files {
		if name == "code/external/mod/retired/api.pb.go" {
			continue
		}
		actual, err := os.ReadFile(filepath.Join(root, name))
		require.NoError(t, err)
		require.Equal(t, body, string(actual))
	}
}
